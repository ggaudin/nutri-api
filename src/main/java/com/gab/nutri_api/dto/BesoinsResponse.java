package com.gab.nutri_api.dto;

public class BesoinsResponse {
	
	private Integer patientId;
	private Integer bej;
	private Integer proteinesMin;
	private Integer proteinesMax;
	private Integer lipidesMin;
	private Integer lipidesMax;
	private Integer glucidesMin;
	private Integer glucidesMax;
	
	
	public Integer getPatientId() {
		return patientId;
	}
	public void setPatientId(Integer patientId) {
		this.patientId = patientId;
	}
	public Integer getBej() {
		return bej;
	}
	public void setBej(Integer bej) {
		this.bej = bej;
	}
	public Integer getProteinesMin() {
		return proteinesMin;
	}
	public void setProteinesMin(Integer proteinesMin) {
		this.proteinesMin = proteinesMin;
	}
	public Integer getProteinesMax() {
		return proteinesMax;
	}
	public void setProteinesMax(Integer proteinesMax) {
		this.proteinesMax = proteinesMax;
	}
	public Integer getLipidesMin() {
		return lipidesMin;
	}
	public void setLipidesMin(Integer lipidesMin) {
		this.lipidesMin = lipidesMin;
	}
	public Integer getLipidesMax() {
		return lipidesMax;
	}
	public void setLipidesMax(Integer lipidesMax) {
		this.lipidesMax = lipidesMax;
	}
	public Integer getGlucidesMin() {
		return glucidesMin;
	}
	public void setGlucidesMin(Integer glucidesMin) {
		this.glucidesMin = glucidesMin;
	}
	public Integer getGlucidesMax() {
		return glucidesMax;
	}
	public void setGlucidesMax(Integer glucidesMax) {
		this.glucidesMax = glucidesMax;
	}
	
	

}
